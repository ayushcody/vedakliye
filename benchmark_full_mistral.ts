import { extractAndGradeMistral } from './src/lib/mistral';
import * as fs from 'fs';
import * as path from 'path';

async function benchmarkFull() {
  console.log("==================================================");
  console.log("STARTING FULL PDF BENCHMARK FOR MISTRAL AI");
  console.log("==================================================");

  const qpDir = 'extracted_full_pages/qp';
  const asDir = 'extracted_full_pages/as';

  const qpFiles = fs.readdirSync(qpDir).filter(f => f.endsWith('.png')).sort();
  const asFiles = fs.readdirSync(asDir).filter(f => f.endsWith('.png')).sort();

  console.log(`Found ${qpFiles.length} Question Paper pages and ${asFiles.length} Answer Sheet pages.`);

  const toDataURL = (filePath: string) => {
    const data = fs.readFileSync(filePath);
    return `data:image/png;base64,${data.toString('base64')}`;
  };

  const qpPages = qpFiles.map(f => toDataURL(path.join(qpDir, f)));
  const asPages = asFiles.map(f => toDataURL(path.join(asDir, f)));

  const overallStartTime = Date.now();
  const stepTimestamps: { step: number; msg: string; time: number; durationSinceLastSec: number }[] = [];
  let lastTime = overallStartTime;

  try {
    const result = await extractAndGradeMistral(qpPages, asPages, (step, msg) => {
      const now = Date.now();
      const duration = (now - lastTime) / 1000;
      lastTime = now;
      console.log(`[TIMING +${duration.toFixed(1)}s] [Progress Step ${step}]: ${msg}`);
      stepTimestamps.push({
        step,
        msg,
        time: now,
        durationSinceLastSec: duration
      });
    });

    const totalDurationSec = (Date.now() - overallStartTime) / 1000;
    console.log("==================================================");
    console.log(`FULL PDF PROCESSING COMPLETED IN ${totalDurationSec.toFixed(1)}s (${(totalDurationSec / 60).toFixed(2)} min)`);
    console.log("==================================================");

    const answeredCount = result.questions.filter(q => q.status === "answered").length;
    const partialCount = result.questions.filter(q => q.status === "partially_answered").length;
    const unansweredCount = result.questions.filter(q => q.status === "unanswered").length;
    const orphanCount = result.orphanAnswers.length;

    const report = {
      model: "mistral-ocr-4-1 + mistral-large-latest",
      totalPages: qpFiles.length + asFiles.length,
      qpPagesCount: qpFiles.length,
      asPagesCount: asFiles.length,
      totalDurationSeconds: totalDurationSec,
      totalDurationMinutes: totalDurationSec / 60,
      totalScore: result.totalScore,
      totalMaxMarks: result.totalMaxMarks,
      statistics: {
        totalQuestionsExtracted: result.questions.length,
        answered: answeredCount,
        partiallyAnswered: partialCount,
        unanswered: unansweredCount,
        orphans: orphanCount
      },
      timingSteps: stepTimestamps,
      resultSummary: result.summary
    };

    fs.mkdirSync('benchmark_experiments', { recursive: true });
    fs.writeFileSync('benchmark_experiments/MISTRAL_FULL_RUN_RESULT.json', JSON.stringify(result, null, 2));
    fs.writeFileSync('benchmark_experiments/MISTRAL_FULL_BENCHMARK_REPORT.json', JSON.stringify(report, null, 2));

    // Also write a markdown report
    const md = `# Mistral AI Full Assessment Benchmark (26 Pages)

## Summary Metrics
- **Total Pages Processed**: ${report.totalPages} (${report.qpPagesCount} QP + ${report.asPagesCount} AS)
- **Total Execution Time**: **${totalDurationSec.toFixed(1)}s** (${(totalDurationSec / 60).toFixed(2)} minutes)
- **Total Score**: ${result.totalScore} / ${result.totalMaxMarks}
- **Total Questions Extracted**: ${result.questions.length}
  - **Fully Answered**: ${answeredCount}
  - **Partially Answered**: ${partialCount}
  - **Unanswered**: ${unansweredCount}
  - **Orphan Answers**: ${orphanCount}

## Overall AI Summary
> ${result.summary.replace(/\n/g, ' ')}

## Detailed Stage Timing Breakdown
| Stage / Step | Event Description | Duration |
|---|---|---|
${stepTimestamps.map(s => `| Step ${s.step} | ${s.msg} | +${s.durationSinceLastSec.toFixed(1)}s |`).join('\n')}

---
*Generated by Veda AI Evaluation Pipeline.*
`;

    fs.writeFileSync('benchmark_experiments/MISTRAL_FULL_BENCHMARK_REPORT.md', md);
    console.log("Saved reports to benchmark_experiments/MISTRAL_FULL_BENCHMARK_REPORT.md");

  } catch (err: any) {
    console.error("Benchmark failed with error:", err);
  }
}

benchmarkFull();
